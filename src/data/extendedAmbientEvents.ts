const t = (text: string): DialogueLine => ({ kind: "thought", text });
const l = (speaker: string, text: string): DialogueLine => ({ speaker, text });

const reward = (
  action: WeeklyAction,
  index: number,
  label: string,
  result: string,
  trustFirst: boolean,
): SceneChoice => {
  const trust = trustFirst ? 4 + (index % 3) : index % 2;
  const ownership = trustFirst ? -1 - (index % 2) : 3 + (index % 3);
  if (action === "work") {
    return {
      label,
      result,
      trust,
      ownership,
      money: trustFirst ? 1100 + (index % 3) * 150 : 1500 + (index % 3) * 200,
      ...(trustFirst && index % 4 === 0 ? { sharedPoints: 1 } : {}),
    };
  }
  if (action === "play") {
    return {
      label,
      result,
      trust,
      ownership,
      money: trustFirst ? -(200 + (index % 3) * 150) : -(400 + (index % 3) * 200),
      ...(trustFirst ? { fighterPoints: 1 + (index % 2) } : { sharedPoints: 2 }),
    };
  }
  if (action === "rest") {
    return {
      label,
      result,
      trust,
      ownership,
      ...(trustFirst ? { condition: "good" as const } : { sharedPoints: 2 + (index % 2) }),
    };
  }
  return {
    label,
    result,
    trust,
    ownership,
    money: trustFirst ? -(350 + (index % 3) * 150) : -(650 + (index % 3) * 200),
    ...(trustFirst ? { fighterPoints: 2 + (index % 2) } : { sharedPoints: 3 + (index % 2) }),
  };
};

