import type {
  DialogueLine,
  SceneDirection,
  SceneSpriteCue,
} from "../game/types";

export interface ProloguePage extends DialogueLine {
  sceneLabel: string;
}

const thought = (text: string, direction?: SceneDirection): DialogueLine => ({
  kind: "thought",
  text,
  direction,
});

const line = (
  speaker: string,
  text: string,
  direction?: SceneDirection,
): DialogueLine => ({ speaker, text, direction });

