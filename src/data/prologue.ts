const scenePages = (
  sceneLabel: string,
  background: string,
  initialSprite: SceneSpriteCue | null,
  lines: DialogueLine[],
): ProloguePage[] =>
  lines.map((entry, index) => ({
    ...entry,
    sceneLabel,
    direction:
      index === 0
        ? {
            background,
            sprite: initialSprite,
            ...entry.direction,
          }
        : entry.direction,
  }));

