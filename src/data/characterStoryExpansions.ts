type Beat = ["t" | "m" | "f", string];

const beats = (fighterName: string, ...entries: Beat[]): DialogueLine[] =>
  entries.map(([voice, text]) =>
    voice === "t"
      ? { kind: "thought", text }
      : { speaker: voice === "m" ? "ミミ" : fighterName, text },
  );

