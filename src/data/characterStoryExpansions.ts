export const withCharacterStoryExpansion = (
  fighterId: string,
  stage: StoryStage,
  scene: CharacterScene,
): CharacterScene => {
  const addition = expansions[fighterId]?.[stage];
  const profile = routeProfiles[fighterId];
  if (!addition?.length || !profile) return scene;
  const frame = routeFrame(profile, stage);
  const mimiLines = mimiStageLines(profile, stage);

  const encounterCg = encounterCgs[fighterId];
  if (stage === "meet" && encounterCg && frame.before[1]) {
    frame.before[1] = {
      ...frame.before[1],
      direction: {
        ...frame.before[1].direction,
        still: encounterCg,
        effect: "pulse",
      },
    };
  }
  const eventCg = eventCgs[fighterId];
  if (eventCg?.stage === stage && frame.before[1]) {
    frame.before[1] = {
      ...frame.before[1],
      direction: {
        ...frame.before[1].direction,
        still: eventCg.path,
        effect: "pulse",
      },
    };
  }

  const [opening, ...remainingSceneLines] = scene.lines;
  const closing = remainingSceneLines.at(-1);
  const coreDialogue = remainingSceneLines.slice(0, -1);
  const frameOpening = frame.before.slice(0, 2);
  const frameTurn = frame.before.slice(2);
  const additionOpening = addition.slice(0, 2);
  const additionTurn = addition.slice(2);
  const dialogueOpening = coreDialogue.slice(0, 2);
  const dialogueTurn = coreDialogue.slice(2);
  const orderedLines = [
    opening,
    frameOpening[0],
    additionOpening[0],
    dialogueOpening[0],
    {
      ...mimiLines.before,
      direction: stageDirections[stage],
    },
    frameOpening[1],
    additionOpening[1],
    dialogueOpening[1],
    frameTurn[0],
    additionTurn[0],
    dialogueTurn[0],
    frameTurn[1],
    additionTurn[1],
    frame.after[0],
    mimiLines.after,
    frame.after[1],
    closing,
    ...frame.after.slice(2),
  ].filter((line): line is DialogueLine => Boolean(line));

  return {
    ...scene,
    lines: orderedLines,
  };
};
